    /**
     * @param args the command line argumentsx
     */
    private void cargarTabla() {
        String[] columnas = {
            "Codigo", "Nombre", "Capacidad", "Ubicación", "Estado"
        };

        String[][] datos = lista.obtenerTodos();

        for (int i = 0; i < datos.length; i++) {
            datos[i][4] = datos[i][4].equals("A") ? "Activo" : "Inactivo";
        }

        jTable1.setModel(new javax.swing.table.DefaultTableModel(datos, columnas));
    }

    class EstadoAmbienteRenderer extends DefaultTableCellRenderer {

        @Override
        public Component getTableCellRendererComponent(
                JTable table, Object value, boolean isSelected,
                boolean hasFocus, int row, int column) {

            Component c = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column);

            String estado = table.getValueAt(row, 4).toString();

            if (estado.equalsIgnoreCase("Inactivo")) {
                c.setBackground(new Color(255, 204, 204)); // rojo suave
            } else {
                c.setBackground(Color.WHITE);
            }

            if (isSelected) {
                c.setBackground(new Color(184, 207, 229));
            }

            return c;
        }
    }

    private void aplicarColores() {
        EstadoAmbienteRenderer renderer = new EstadoAmbienteRenderer();

        for (int i = 0; i < jTable1.getColumnCount(); i++) {
            jTable1.getColumnModel().getColumn(i).setCellRenderer(renderer);
        }
    }


