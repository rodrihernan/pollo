    private void btnRegistrar5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar5ActionPerformed
        // TODO add your handling code here:

        String codigo = txtCodigo.getText().trim();
        programacionActual = listaProgramaciones.buscarPorCodigo(codigo);

        if (programacionActual == null) {
            JOptionPane.showMessageDialog(this, "Programación no encontrada");
            return;
        }

        // Cargar datos en los campos
        txtNombre.setText(programacionActual.getNombrePro());
        jDateChooser1.setDate(programacionActual.getMesini());
        jDateChooser2.setDate(programacionActual.getMesfin());
        jComboBox1.setSelectedItem(programacionActual.getHorario());
        JcbSeccion.setSelectedItem(String.valueOf(programacionActual.getSección()));
        jSpinner1.setValue(programacionActual.getCapacidad());

        docenteSeleccionado = programacionActual.getDoc();
        ambienteSeleccionado = programacionActual.getAmbi();
        deporteSeleccionado = programacionActual.getDepor();

        jTextField3.setText(docenteSeleccionado.getNombre());
        jTextField6.setText(ambienteSeleccionado.getNombre());
        jTextField8.setText(deporteSeleccionado.getNombreDep());

        JOptionPane.showMessageDialog(this, "Programación cargada");
    }//GEN-LAST:event_btnRegistrar5ActionPerformed

