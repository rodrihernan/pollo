    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (programacionActual == null) {
            JOptionPane.showMessageDialog(this, "Primero busque una programación");
            return;
        }

        programacionActual.setNombrePro(txtNombre.getText());
        programacionActual.setMesini(jDateChooser1.getDate());
        programacionActual.setMesfin(jDateChooser2.getDate());
        programacionActual.setHorario(jComboBox1.getSelectedItem().toString());
        programacionActual.setCapacidad((int) jSpinner1.getValue());
        programacionActual.setSección(JcbSeccion.getSelectedItem().toString().charAt(0));

        programacionActual.setDoc(docenteSeleccionado);
        programacionActual.setAmbi(ambienteSeleccionado);
        programacionActual.setDepor(deporteSeleccionado);

        JOptionPane.showMessageDialog(this, "Programación modificada correctamente");
        this.dispose();

    }//GEN-LAST:event_btnRegistrarActionPerformed

