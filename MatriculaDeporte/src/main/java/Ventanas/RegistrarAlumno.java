    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (txtCodigo.getText().trim().isEmpty()
                || txtNombre.getText().trim().isEmpty()
                || txtApellido.getText().trim().isEmpty()
                || txtDni.getText().trim().isEmpty()
                || txtDireccion.getText().trim().isEmpty()
                || txtTelefono.getText().trim().isEmpty()
                || txtTalla.getText().trim().isEmpty()
                || JdFechaNac.getDate() == null
                || (!Femenino.isSelected() && !Masculino.isSelected()
                || ((Number) JsPeso.getValue()).doubleValue() <= 0)) {

            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        String codigo = txtCodigo.getText().trim();

        if (lista.buscar(codigo) != null) {
            JOptionPane.showMessageDialog(this, "Ya existe un alumno con ese código.");
            return;
        }

        Date fecha = JdFechaNac.getDate();
        if (fecha == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una fecha de nacimiento.");
            return;
        }

        char genero;
        if (Femenino.isSelected()) {
            genero = 'F';
        } else if (Masculino.isSelected()) {
            genero = 'M';
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione el género.");
            return;
        }

        Alumno alu = new Alumno(
                txtTalla.getText().trim(),
                Float.parseFloat(JsPeso.getValue().toString()),
                true,
                txtNombre.getText().trim(),
                txtApellido.getText().trim(),
                txtDni.getText().trim(),
                codigo,
                fecha,
                genero,
                txtDireccion.getText().trim(),
                txtTelefono.getText().trim()
        );

        lista.insertarInicio(alu);
        this.lista.guardarAlumnoEnArchivo(alu);

        JOptionPane.showMessageDialog(this, "Alumno registrado correctamente.");

        // Limpiar campos
        txtCodigo.setText("");
        txtNombre.setText("");
        txtApellido.setText("");
        txtDni.setText("");
        txtDireccion.setText("");
        txtTelefono.setText("");
        txtTalla.setText("");
        JsPeso.setValue(0);
        JdFechaNac.setDate(null);
        Femenino.setSelected(false);
        Masculino.setSelected(false);
    }//GEN-LAST:event_btnRegistrarActionPerformed

