    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        if (matriculaActual == null) {
            JOptionPane.showMessageDialog(this, "Primero busque una matrícula");
            return;
        }

        int op = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de eliminar la matrícula?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );

        if (op == JOptionPane.YES_OPTION) {
            listaMatriculas.eliminarPorID(matriculaActual.getIdMatricula());
            JOptionPane.showMessageDialog(this, "Matrícula eliminada");
            limpiar();
            matriculaActual = null;
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

