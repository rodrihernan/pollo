    private void btnBuscar6ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscar6ActionPerformed
        // TODO add your handling code here:

        String id = txtAlumno.getText().trim();

        if (id.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese ID de matrícula");
            return;
        }

        Matricula m = listaMatriculas.buscarPorID(id);

        if (m == null) {
            JOptionPane.showMessageDialog(this, "Matrícula no encontrada");
            return;
        }

        matriculaActual = m;

        // Mostrar datos
        jDateChooser1.setDate(m.getFechaMatricula());
        jSpinner1.setValue(m.getCosto());

        txtCosto.setText(m.getAlu().getCodigo());
        txtDocente.setText(m.getAlu().getNombre());
        txtDocente1.setText(m.getAlu().getApellido());

        txtCampos.setText(m.getTra().getCodigo());
        txtDeporte2.setText(m.getTra().getNombre());
        txtDeporte1.setText(m.getTra().getApellido());

        txtDeporte3.setText(m.getGrupo().getCodigoc());
        txtDeporte.setText(m.getGrupo().getNombrePro());

        txtDeporte6.setText("ACTIVA");
    }//GEN-LAST:event_btnBuscar6ActionPerformed

