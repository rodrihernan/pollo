    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String codigo = txtCodigo.getText().trim().toUpperCase();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese código");
            return;
        }

        deporteEncontrado = lista.buscar(codigo);

        if (deporteEncontrado == null) {
            JOptionPane.showMessageDialog(this, "Deporte no encontrado");
            limpiarCampos();
            return;
        }

        txtNombre.setText(deporteEncontrado.getNombreDep());
        txtDescripcion.setText(deporteEncontrado.getDescripcion());
        cmbCategoria.setSelectedItem(
                deporteEncontrado.getCategoria() == 'G' ? "Grupal" : "Individual"
        );

        
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnInhabilitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInhabilitarActionPerformed
        if (deporteEncontrado == null) {
            JOptionPane.showMessageDialog(this, "Primero busque un deporte");
            return;
        }

        if (!deporteEncontrado.getHabilitado()) {
            JOptionPane.showMessageDialog(this, "El deporte ya está inhabilitado");
            return;
        }

        int r = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de inhabilitar este deporte?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );

        if (r == JOptionPane.YES_OPTION) {
            deporteEncontrado.setHabilitado(false);
            JOptionPane.showMessageDialog(this, "Deporte inhabilitado correctamente");
            limpiarCampos();
            deporteEncontrado = null;
        }

    }//GEN-LAST:event_btnInhabilitarActionPerformed
    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");
        cmbCategoria.setSelectedIndex(0);
        txtCodigo.setEnabled(true);
        txtCodigo.requestFocus();
    }

