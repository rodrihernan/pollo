    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        
        String codPago = txtCodigo.getText();
        Pago p = listaPagos.buscarPorCodigo(codPago);

        if (p == null) {
            JOptionPane.showMessageDialog(this, "Pago no encontrado");
            return;
        }

        if (txtMonto.getText().isEmpty() || JdcFecha.getDate() == null
                || (!RbtnPago.isSelected() && !RbtnMoroso.isSelected())) {
            JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        try {
            int monto = Integer.parseInt(txtMonto.getText());
            p.setMonto(monto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Monto inválido");
            return;
        }

        p.setFechaPago(JdcFecha.getDate());
        p.setEstado(RbtnPago.isSelected() ? 'P' : 'M');

        JOptionPane.showMessageDialog(this, "Pago modificado correctamente");

    }//GEN-LAST:event_btnModificarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        Pago p = listaPagos.buscarPorCodigo(txtCodigo.getText());

        if (p != null) {
            txtMonto.setText(String.valueOf(p.getMonto()));
            JdcFecha.setDate(p.getFechaPago());

            if (p.getEstado() == 'P') {
                RbtnPago.setSelected(true);
            } else {
                RbtnMoroso.setSelected(true);
            }
        } else {
            JOptionPane.showMessageDialog(this, "Pago no encontrado");
        }
        
    }//GEN-LAST:event_btnBuscarActionPerformed


