    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String codigo = txtCodigo.getText().trim().toUpperCase();
        String nombre = txtNombre.getText().trim();
        String descripcion = txtDescripcion.getText().trim();

        if (codigo.isEmpty() || nombre.isEmpty() || descripcion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Complete los campos obligatorios");
            return;
        }

        // validar duplicado
        if (lista.buscar(codigo) != null) {
            JOptionPane.showMessageDialog(this, "El código ya existe");
            return;
        }

        char categoria = cmbCategoria.getSelectedItem().equals("Grupal") ? 'G' : 'I';

        Deporte dep = new Deporte(codigo, nombre, categoria, descripcion);
        lista.insertarAlFinal(dep);
        this.lista.guardarDeporteEnArchivo(dep);

        JOptionPane.showMessageDialog(this, "Deporte registrado correctamente");
        limpiarCampos();

    }

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtDescripcion.setText("");
        cmbCategoria.setSelectedIndex(0); // vuelve al primer item
        txtCodigo.requestFocus();

    }//GEN-LAST:event_btnRegistrarActionPerformed

