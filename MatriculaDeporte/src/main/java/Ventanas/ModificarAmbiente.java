    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed

        String codigo = txtCodigo.getText().trim();

        Ambiente amb = lista.buscar(codigo);

        if (amb == null) {
            JOptionPane.showMessageDialog(this, "No existe un ambiente con ese código.");
            return;
        }

        // Cargar datos
        txtTelefono.setText(amb.getNombre());
        txtGenero.setText(amb.getUbicacion());
        JsCapacidad.setValue(amb.getCapacidad());

        if (amb.getEstado() == 'A') {
            RbtnActivo.setSelected(true);
            RbtnInactivo.setSelected(false);
        } else {
            RbtnActivo.setSelected(false);
            RbtnInactivo.setSelected(true);
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        String codigo = txtCodigo.getText().trim();

        Ambiente amb = lista.buscar(codigo);

        if (amb == null) {
            JOptionPane.showMessageDialog(this, "No existe un ambiente con ese código.");
            return;
        }

        // Guardar nuevos valores
        amb.setNombre(txtTelefono.getText());
        amb.setUbicacion(txtGenero.getText());
        amb.setCapacidad((int) JsCapacidad.getValue());

        if (RbtnActivo.isSelected()) {
            amb.setEstado('A');
        } else {
            amb.setEstado('I');
        }

        JOptionPane.showMessageDialog(this, "Ambiente modificado correctamente.");
    }//GEN-LAST:event_btnModificarActionPerformed

