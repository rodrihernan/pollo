    private void btnRegistrar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar1ActionPerformed
        // TODO add your handling code here:
        String codigo = txtDocente.getText().trim();

        Docente d = listaDocentes.buscar(codigo);

        if (d == null || !d.isHabilitado()) {
            JOptionPane.showMessageDialog(this, "Docente no encontrado o inhabilitado");
            return;
        }

        docenteSeleccionado = d;
        jTextField4.setText(d.getNombre() + " " + d.getApellido());
    }//GEN-LAST:event_btnRegistrar1ActionPerformed

