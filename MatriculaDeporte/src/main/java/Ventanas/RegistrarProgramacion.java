    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // 1. Obtener datos
        String codigo = txtCodigo.getText().trim();
        String docente = txtDocente.getText().trim();
        String ambiente = txtAmbiente.getText().trim();
        String deporte = txtDeporte.getText().trim();
        String nombre = txtNombre.getText().trim();
        Date mesIni = jDateChooser1.getDate();
        Date mesFin = jDateChooser2.getDate();
        String horario = jComboBox1.getSelectedItem().toString();
        int capacidad = (int) JsCapacidad.getValue();
        char seccion = JcbSeccion.getSelectedItem().toString().charAt(0);

        // 2. Validaciones básicas
        if (codigo.isEmpty() || nombre.isEmpty() || mesIni == null || mesFin == null ||docente.isEmpty()||ambiente.isEmpty()||deporte.isEmpty()|| capacidad <= 0){
            JOptionPane.showMessageDialog(this, "Complete todos los campos");
            return;
        }

        if (capacidad < 10 || capacidad > 20) {
            JOptionPane.showMessageDialog(this, "Capacidad debe ser entre 10 y 20");
            return;
        }

        if (mesIni.after(mesFin)) {
            JOptionPane.showMessageDialog(this, "Fechas incorrectas");
            return;
        }

        // 3. Objetos ya buscados (desde botones Buscar)
        if (docenteSeleccionado == null
                || ambienteSeleccionado == null
                || deporteSeleccionado == null) {

            JOptionPane.showMessageDialog(this, "Debe seleccionar docente, ambiente y deporte");
            return;
        }

        // 4. Verificar duplicado
        if (listaProgramaciones.buscar(codigo, seccion) != null) {
            JOptionPane.showMessageDialog(this, "Ya existe esa programación");
            return;
        }

        // 5. Crear programación
        Programacion p = new Programacion(mesIni, mesFin, horario, docenteSeleccionado, ambienteSeleccionado, deporteSeleccionado, capacidad, seccion, codigo, nombre
        );

        listaProgramaciones.insertarAlFinal(p);

        JOptionPane.showMessageDialog(this, "Programación registrada correctamente");
        this.dispose();
    }//GEN-LAST:event_btnRegistrarActionPerformed

