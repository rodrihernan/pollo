    private void btnRegistrar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar1ActionPerformed
        // TODO add your handling code here:
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese código");
            return;
        }

        docenteActual = listaDocentes.buscar(codigo);

        if (docenteActual == null) {
            JOptionPane.showMessageDialog(this, "Docente no encontrado");
            limpiarCampos();
            return;
        }

        // Cargar datos al formulario
        txtNombre.setText(docenteActual.getNombre());
        txtApellido.setText(docenteActual.getApellido());
        txtDni.setText(docenteActual.getDni());
        txtDireccion.setText(docenteActual.getEspecialidad());
        txtTelefono1.setText(docenteActual.getTelefono());
        txtTelefono2.setText(docenteActual.getDireccion());

        jSpinner1.setValue(docenteActual.getAniosExperiencia());
        jDateChooser1.setDate(docenteActual.getFechNaci());

        if (docenteActual.getGenero() == 'F') {
            jRadioButton1.setSelected(true);
            jRadioButton2.setSelected(false);
        } else {
            jRadioButton2.setSelected(true);
            jRadioButton1.setSelected(false);
        }
    }//GEN-LAST:event_btnRegistrar1ActionPerformed

    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        if (docenteActual == null) {
            JOptionPane.showMessageDialog(this, "Primero busque un docente");
            return;
        }

        // Actualizar datos
        docenteActual.setNombre(txtNombre.getText());
        docenteActual.setApellido(txtApellido.getText());
        docenteActual.setDni(txtDni.getText());
        docenteActual.setTelefono(txtTelefono1.getText());
        docenteActual.setDireccion(txtTelefono2.getText());
        docenteActual.setEspecialidad(txtDireccion.getText());
        docenteActual.setAniosExperiencia((int) jSpinner1.getValue());
        docenteActual.setFechNaci(jDateChooser1.getDate());

        char genero = jRadioButton1.isSelected() ? 'F' : 'M';
        docenteActual.setGenero(genero);

        JOptionPane.showMessageDialog(this, "Docente modificado correctamente");
    }//GEN-LAST:event_btnRegistrarActionPerformed

