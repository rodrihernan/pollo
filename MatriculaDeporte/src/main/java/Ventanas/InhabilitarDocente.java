    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código.");
            return;
        }
        
        String codigo = txtCodigo.getText().trim();

        Docente doc = lista.buscar(codigo);

        if (doc == null) {
            JOptionPane.showMessageDialog(this, "Docente no encontrado");
            return;
        }

        txtNombre.setText(doc.getNombre());
        txtApellido.setText(doc.getApellido());
        txtDni.setText(doc.getDni());
        txtDireccion.setText(doc.getEspecialidad());
        txtTelefono1.setText(doc.getTelefono());
        txtTelefono2.setText(doc.getDireccion());

        jSpinner1.setValue(doc.getAniosExperiencia());
        jDateChooser1.setDate(doc.getFechNaci());

        if (doc.getGenero() == 'F') {
            Femenino.setSelected(true);
        } else {
            Masculino.setSelected(true);
        }
        if (!doc.isHabilitado()) {
            JOptionPane.showMessageDialog(this, "⚠ El alumno ya está INHABILITADO.");
        }
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnInhabilitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInhabilitarActionPerformed
        if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código.");
            return;
        }

        String codigo = txtCodigo.getText().trim();

        Docente doc = lista.buscar(codigo);

        if (doc == null) {
            JOptionPane.showMessageDialog(this, "Primero busque un docente");
            return;
        }
        if (!doc.isHabilitado()) {
            JOptionPane.showMessageDialog(this, "El Docente ya está inhabilitado.");
            return;
        }

        int r = JOptionPane.showConfirmDialog(
                this,
                "¿Está seguro de inhabilitar al docente?",
                "Confirmar",
                JOptionPane.YES_NO_OPTION
        );

        if (r == JOptionPane.YES_OPTION) {
            doc.setHabilitado(false);
            JOptionPane.showMessageDialog(this, "Docente inhabilitado correctamente");
            this.dispose();
        }
    }//GEN-LAST:event_btnInhabilitarActionPerformed

