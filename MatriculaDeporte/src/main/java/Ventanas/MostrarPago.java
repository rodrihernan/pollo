    private void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0); // limpiar tabla

        NodoPago actual = listaPagos.getCabeza();

        while (actual != null) {
            Pago p = actual.getDato();

            String estadoTexto = (p.getEstado() == 'P') ? "Pagó" : "Moroso";

            Object[] fila = {
                p.getCodigoPgo(),
                p.getMonto(),
                p.getFechaPago(),
                estadoTexto
            };

            modelo.addRow(fila);
            actual = actual.getSiguiente();
        }
    }

