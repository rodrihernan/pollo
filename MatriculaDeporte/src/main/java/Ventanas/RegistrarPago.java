    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        
        if (matriculaEncontrada == null) {
            JOptionPane.showMessageDialog(this, "Primero busque una matrícula");
            return;
        }

        Alumno a = matriculaEncontrada.getAlu();
        if (!a.isHabilitado()) {
            JOptionPane.showMessageDialog(this,
                    "El alumno no está habilitado para realizar pagos");
            return;
        }

        if (JdcFecha.getDate() == null) {
            JOptionPane.showMessageDialog(this, "Seleccione una fecha");
            return;
        }
        
        if (!RbtnPago.isSelected() && !RbtnMoroso.isSelected()) {
            JOptionPane.showMessageDialog(this, "Seleccione el estado del pago");
            return;
        }

        char estado = RbtnPago.isSelected() ? 'P' : 'M';

        Pago p = new Pago(
                txtCodigo.getText().trim(),
                estado,
                (int) matriculaEncontrada.getCosto(),
                JdcFecha.getDate()
        );

        listaPagos.insertarAlFinal(p);
        matriculaEncontrada.setPag(p);

        JOptionPane.showMessageDialog(this, "Pago registrado correctamente");
        limpiarCampos();
        
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void limpiarCampos() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtMonto.setText("");
        JdcFecha.setDate(null);
        RbtnPago.setSelected(false);
        RbtnMoroso.setSelected(false);
        txtNombre.setEditable(true);
        txtMonto.setEditable(true);
        matriculaEncontrada = null;
    }
    
