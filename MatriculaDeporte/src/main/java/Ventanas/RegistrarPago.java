    private void btnBuscar4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscar4ActionPerformed
        
        String codigo = txtCodigo.getText().trim();

        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese código de matrícula");
            return;
        }

        matriculaEncontrada = listaMatriculas.buscarPorID(codigo);

        if (matriculaEncontrada == null) {
            JOptionPane.showMessageDialog(this, "Matrícula no encontrada");
            limpiarCampos();
            return;
        }

        txtNombre.setText(
                matriculaEncontrada.getAlu().getNombre() + " "
                + matriculaEncontrada.getAlu().getApellido()
        );

        txtMonto.setText(
                String.valueOf(matriculaEncontrada.getCosto())
        );

        txtNombre.setEditable(false);
        txtMonto.setEditable(false);
            
    }//GEN-LAST:event_btnBuscar4ActionPerformed

