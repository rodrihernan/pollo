    private void btnModifcarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModifcarActionPerformed
         if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Primero busque un trabajador mediante su código.");
            return;
        }

        String codigo = txtCodigo.getText().trim();
        Trabajador tra = lista.buscar(codigo);

        if (tra == null) {
            JOptionPane.showMessageDialog(this, "No existe un Trabajador con ese código.");
            return;
        }
        if (txtCodigo.getText().trim().isEmpty()
                || txtNombre.getText().trim().isEmpty()
                || txtApellido.getText().trim().isEmpty()
                || txtDni.getText().trim().isEmpty()
                || txtDireccion.getText().trim().isEmpty()
                || txtTelefono.getText().trim().isEmpty()
                || JdFechaNac.getDate() == null
                || (!Femenino.isSelected() && !Masculino.isSelected())) {

            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }

        tra.setNombre(txtNombre.getText().trim());
        tra.setApellido(txtApellido.getText().trim());
        tra.setDni(txtDni.getText().trim());
        tra.setDireccion(txtDireccion.getText().trim());
        tra.setTelefono(txtTelefono.getText().trim());
        tra.setFechNaci(JdFechaNac.getDate());

        // Actualizar Género
        if (Femenino.isSelected()) {
            tra.setGenero('F');
        } else if (Masculino.isSelected()) {
            tra.setGenero('M');
        }

        // ACTUALIZAR DATOS DE TRABAJADOR
        tra.setCargo(JcbCargo.getSelectedItem().toString());
        tra.setTurno(JcbTurno.getSelectedItem().toString());

        JOptionPane.showMessageDialog(this, "Trabajador modificado correctamente.");
    }//GEN-LAST:event_btnModifcarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        if (txtCodigo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código para buscar.");
            return;
        }

        String codigo = txtCodigo.getText().trim();
        Trabajador tra = lista.buscar(codigo);

        if (tra == null) {
            JOptionPane.showMessageDialog(this, "Trabajador no encontrado.");
            return;
        }

        // CARGAR LOS DATOS DEL TRABAJADOR
        txtNombre.setText(tra.getNombre());
        txtApellido.setText(tra.getApellido());
        txtDni.setText(tra.getDni());
        txtDireccion.setText(tra.getDireccion());
        txtTelefono.setText(tra.getTelefono());
        JdFechaNac.setDate(tra.getFechNaci());

        // Cargar Género
        if (tra.getGenero() == 'F') {
            Femenino.setSelected(true);
            Masculino.setSelected(false);
        } else if (tra.getGenero() == 'M') {
            Masculino.setSelected(true);
            Femenino.setSelected(false);
        }

        JcbCargo.setSelectedItem(tra.getCargo());
        JcbTurno.setSelectedItem(tra.getTurno());
    }//GEN-LAST:event_btnBuscarActionPerformed

