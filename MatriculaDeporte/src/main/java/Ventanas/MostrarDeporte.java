    private void inicializarTabla() {
        modelo = new DefaultTableModel(
                null,
                new String[]{"Cod.Deporte", "Nombre", "Categoria", "Descripción", "Estado"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        tablaDeportes.setModel(modelo);
    }

    private void cargarTabla() {
        modelo.setRowCount(0);

        NodoDeporte actual = lista.getCabeza();

        while (actual != null) {
            Deporte d = actual.getDato();

            modelo.addRow(new Object[]{
                d.getCodigoDep(),
                d.getNombreDep(),
                d.getCategoria() == 'G' ? "Grupal" : "Individual",
                d.getDescripcion(),
                d.getHabilitado() ? "Habilitado" : "Inhabilitado"
            });

            actual = actual.getSiguiente();
        }
    }

    private void colorearFilas() {
        tablaDeportes.setDefaultRenderer(Object.class, new javax.swing.table.DefaultTableCellRenderer() {

            @Override
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {

                java.awt.Component c = super.getTableCellRendererComponent(
                        table, value, isSelected, hasFocus, row, column
                );

                String estado = table.getValueAt(row, 4).toString();

                if (estado.equals("Inhabilitado")) {
                    c.setBackground(new java.awt.Color(255, 200, 200)); // rojo suave
                } else {
                    c.setBackground(java.awt.Color.WHITE);
                }

                if (isSelected) {
                    c.setBackground(new java.awt.Color(184, 207, 229));
                }

                return c;
            }
        });
    }

