    private void configurarTabla() {
        DefaultTableModel modelo = new DefaultTableModel();
        modelo.addColumn("ID Matrícula");
        modelo.addColumn("Fecha");
        modelo.addColumn("Alumno");
        modelo.addColumn("Programa");
        modelo.addColumn("Costo");

        jTable1.setModel(modelo);
    }

    private void cargarTodos() {

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        if (listaMatriculas == null || listaMatriculas.getTamaño() == 0) {
            return;
        }

        NodoMatricula aux = listaMatriculas.getCabeza();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        while (aux != null) {

            Matricula m = aux.getDato();

            Object[] fila = {
                m.getIdMatricula(),
                sdf.format(m.getFechaMatricula()),
                m.getAlu().getNombre() + " " + m.getAlu().getApellido(),
                m.getGrupo().getNombrePro(),
                m.getCosto()
            };

            modelo.addRow(fila);
            aux = aux.getSiguiente();
        }
    }

