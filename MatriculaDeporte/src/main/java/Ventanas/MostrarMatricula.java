    private void btnRegistrar3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrar3ActionPerformed
        // TODO add your handling code here:
        String codAlumno = jTextField9.getText().trim();

        if (codAlumno.isEmpty()) {
            cargarTodos();
            return;
        }

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0);

        NodoMatricula aux = listaMatriculas.getCabeza();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        while (aux != null) {

            Matricula m = aux.getDato();

            if (m.getAlu().getCodigo().equalsIgnoreCase(codAlumno)) {

                Object[] fila = {
                    m.getIdMatricula(),
                    sdf.format(m.getFechaMatricula()),
                    m.getAlu().getNombre() + " " + m.getAlu().getApellido(),
                    m.getGrupo().getNombrePro(),
                    m.getCosto()
                };

                modelo.addRow(fila);
            }

            aux = aux.getSiguiente();
        }
    }//GEN-LAST:event_btnRegistrar3ActionPerformed

