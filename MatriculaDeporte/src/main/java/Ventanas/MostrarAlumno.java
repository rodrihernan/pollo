    /**
     * @param args the command line arguments
     */
    private void cargarTabla() {

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();
        modelo.setRowCount(0); // limpiar tabla

        if (lista == null) {
            return;
        }

        NodoAlumno aux = lista.getInicio(); 
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        while (aux != null) {

            Alumno a = aux.getDato();

            String estado = a.isHabilitado() ? "Habilitado" : "Inhabilitado";

            Object[] fila = {
                a.getCodigo(),
                a.getNombre(),
                a.getApellido(),
                a.getDni(),
                a.getDireccion(),
                sdf.format(a.getFechNaci()),
                a.getTelefono(),
                a.getGenero(),
                a.getTalla(),
                a.getPeso(),
                estado
            };

            modelo.addRow(fila);
            aux = aux.getSig();
        }
    }

    class EstadoAlumnoRenderer extends DefaultTableCellRenderer {

        @Override
        public Component getTableCellRendererComponent(
                JTable table, Object value, boolean isSelected,
                boolean hasFocus, int row, int column) {

            Component c = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column);

            String estado = table.getValueAt(row, 10).toString();

            if (estado.equalsIgnoreCase("Inhabilitado")) {
                c.setBackground(new Color(255, 204, 204)); // rojo suave
            } else {
                c.setBackground(Color.WHITE);
            }

            // Mantener selección visible
            if (isSelected) {
                c.setBackground(new Color(184, 207, 229));
            }
            return c;
        }
    }

    private void aplicarColores() {
        EstadoAlumnoRenderer renderer = new EstadoAlumnoRenderer();

        for (int i = 0; i < jTable1.getColumnCount(); i++) {
            jTable1.getColumnModel().getColumn(i).setCellRenderer(renderer);
        }
    }


