    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        
        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String ubicacion = txtUbicacion.getText().trim();
        int capacidad = (Integer) JsCapacidad.getValue();
        char estado;
// Validar código
        if (codigo.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el código.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese el nombre.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (ubicacion.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese la ubicación.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (capacidad <= 0) {
            JOptionPane.showMessageDialog(this, "Capacidad debe ser mayor a cero.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Validar estado
        if (RbtnActivo.isSelected()) {
            estado = 'A';
        } else if (RbtnInactivo.isSelected()) {
            estado = 'I';
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione un estado.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Verificar si ya existe
        if (listaAmbientes.buscar(codigo) != null) {
            JOptionPane.showMessageDialog(this, "El código ya existe.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Crear ambiente
        Ambiente nuevo = new Ambiente(codigo, nombre, capacidad, ubicacion, estado);

        // Insertar en la lista
        listaAmbientes.insertarInicio(nuevo);
        this.listaAmbientes.guardarAmbienteEnArchivo(nuevo);
        JOptionPane.showMessageDialog(this, "Ambiente registrado correctamente.");

        // Limpiar campos
        txtCodigo.setText("");
        txtNombre.setText("");
        txtUbicacion.setText("");
        JsCapacidad.setValue(0);
        RbtnActivo.setSelected(false);
        RbtnInactivo.setSelected(false);

    }//GEN-LAST:event_btnRegistrarActionPerformed

