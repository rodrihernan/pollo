    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        
        if (txtCodigo5.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código.");
            return;
        }

        String codigo = txtCodigo5.getText().trim();

        Alumno alu = lista.buscar(codigo);

        if (alu == null) {
            JOptionPane.showMessageDialog(this, "Alumno no encontrado.");
            return;
        }

        txtNombre.setText(alu.getNombre());
        txtApellido.setText(alu.getApellido());
        txtDni.setText(alu.getDni());
        txtDireccion.setText(alu.getDireccion());
        txtTelefono.setText(alu.getTelefono());
        txtTalla.setText(alu.getTalla());
        JsPeso.setValue(alu.getPeso());
        JdFechaNac.setDate(alu.getFechNaci());

        if (alu.getGenero() == 'F') {
            Femenino.setSelected(true);
        } else {
            Masculino.setSelected(true);
        }

        if (!alu.isHabilitado()) {
            JOptionPane.showMessageDialog(this, "⚠ El alumno ya está INHABILITADO.");
        }

    }//GEN-LAST:event_btnBuscarActionPerformed

