    private void btnInhabilitarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInhabilitarActionPerformed
        if (txtCodigo5.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese un código.");
            return;
        }

        String codigo = txtCodigo5.getText().trim();

        Alumno alu = lista.buscar(codigo);

        if (alu == null) {
            JOptionPane.showMessageDialog(this, "Alumno no encontrado.");
            return;
        }

        if (!alu.isHabilitado()) {
            JOptionPane.showMessageDialog(this, "El alumno ya está inhabilitado.");
            return;
        }

        int r = JOptionPane.showConfirmDialog(
                this,
                "¿Desea INHABILITAR al alumno?",
                "Confirmación",
                JOptionPane.YES_NO_OPTION
        );

        if (r == JOptionPane.YES_OPTION) {
            alu.setHabilitado(false);
            JOptionPane.showMessageDialog(this, "Alumno inhabilitado correctamente.");
            limpiarCampos();
        }


    }//GEN-LAST:event_btnInhabilitarActionPerformed

