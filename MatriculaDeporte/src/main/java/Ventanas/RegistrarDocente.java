    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed

        if (txtCodigo.getText().trim().isEmpty()
                || txtDni.getText().trim().isEmpty()
                || txtApellido.getText().trim().isEmpty()
                || txtNombre.getText().trim().isEmpty()
                || txtEspecidalidad.getText().trim().isEmpty()
                || txtDireccion.getText().trim().isEmpty()
                || txtTelefono.getText().trim().isEmpty()
                || JdFechaNac.getDate() == null
                || (!Femenino.isSelected() && !Masculino.isSelected()
                || ((Number) JsAniosExp.getValue()).doubleValue() <= 0)) {

            JOptionPane.showMessageDialog(this, "Complete todos los campos.");
            return;
        }
        // Verificar duplicado
        if (listaDocentes.buscar(txtCodigo.getText()) != null) {
            JOptionPane.showMessageDialog(this, "El código ya existe");
            return;
        }
        // Datos personales
        String codigo = txtCodigo.getText();
        String nombre = txtDni.getText();
        String apellido = txtApellido.getText();
        String dni = txtNombre.getText();
        Date fechaNac = JdFechaNac.getDate();
        char genero = Femenino.isSelected() ? 'F' : 'M';
        String direccion = txtDireccion.getText();
        String telefono = txtTelefono.getText();
        String especialidad = txtEspecidalidad.getText();
        int experiencia = (int) JsAniosExp.getValue();
        Docente d = new Docente(
                especialidad,
                experiencia,
                nombre,
                apellido,
                dni,
                codigo,
                fechaNac,
                genero,
                direccion,
                telefono
        );

        listaDocentes.insertar(d);
        this.listaDocentes.guardarDocenteEnArchivo(d);

        JOptionPane.showMessageDialog(this, "Docente registrado correctamente");
        limpiar();
    }//GEN-LAST:event_btnRegistrarActionPerformed

