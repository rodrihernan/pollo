    public void cargarTabla() {
        DefaultTableModel modelo = (DefaultTableModel) TablaTrabajador.getModel();
        modelo.setRowCount(0); // limpiar tabla

        if (lista == null) {
            return;
        }
    
        NodoTrabajador aux = this.lista.getCab();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");

        while (aux != null) {
            Trabajador tra = aux.getDato();
            // Formatear la fecha
            String fechaNacFormateada = "";

            if (tra.getFechNaci() != null) {
                fechaNacFormateada = sdf.format(tra.getFechNaci());
            }
            String estado = tra.getHabilitado() ? "Habilitado" : "Inhabilitado";

            Object fila[] = {
                tra.getCodigo(),
                tra.getNombre(),
                tra.getApellido(),
                tra.getDni(),
                fechaNacFormateada,
                tra.getTelefono(),
                tra.getDireccion(),
                tra.getGenero(),
                tra.getTurno(),
                tra.getCargo(),
                estado};

            modelo.addRow(fila);
            aux  = aux .getSig();
        }
        this.TablaTrabajador.setModel(modelo);
    }
        class EstadoTrabajadorRenderer extends DefaultTableCellRenderer {

        @Override
        public Component getTableCellRendererComponent(
                JTable table, Object value, boolean isSelected,
                boolean hasFocus, int row, int column) {

            Component c = super.getTableCellRendererComponent(
                    table, value, isSelected, hasFocus, row, column);

            // Columna "Estado" = índice 10
            String estado = table.getValueAt(row, 10).toString();

            if (estado.equalsIgnoreCase("Inhabilitado")) {
                c.setBackground(new Color(255, 204, 204)); // rojo suave
            } else {
                c.setBackground(Color.WHITE);
            }

            // Mantener selección visible
                if (isSelected) {
                    c.setBackground(new Color(184, 207, 229));
                }

                return c;
            }
}
            private void aplicarColores() {
                EstadoTrabajadorRenderer renderer = new EstadoTrabajadorRenderer();

                for (int i = 0; i < TablaTrabajador.getColumnCount(); i++) {
                    TablaTrabajador.getColumnModel().getColumn(i).setCellRenderer(renderer);
                }
            }

